void displayStart() {
  Wire.begin(I2C_SDA, I2C_SCL);
  if (!display.begin(SSD1306_SWITCHCAPVCC, SCREEN_ADDRESS)) {
    Serial.println(F("SSD1306 allocation failed"));
    for (;;)
      ;  // Don't proceed, loop forever
  }

  display.clearDisplay();

  // Переворот дисплея (додати або змінити на іншу орієнтацію)
  display.setRotation(3);  // 0 - нормальна орієнтація, 2 - перевернута

  display.setTextSize(1);               // Розмір тексту
  display.setTextColor(SSD1306_WHITE);  // Колір тексту
  display.setCursor(0, 0);              // Початкова позиція курсора

  display.println(F("Hello, World!"));
  display.display();
}

